"""Regenerate ../database/schema.sql and ../database/seed.sql from app/models.py and app/seed.py.

Usage (from "Madrasa Admin Project/"):  python tools/gen_schema_sql.py
schema.sql = exactly what SQLAlchemy create_all() runs for app/models.py, with an FK/index/ON DELETE
summary at the top; seed.sql = the demo data the app seeds on first start (no administrator; sample
teachers disabled). tests/test_package_layout.py fails when either file drifts from the models.
No SQL strings are built here: rows are read with SQLAlchemy select() and values are escaped by q().
"""

import os
import sys
import tempfile
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent
ROOT = PROJECT.parent
tmp = Path(tempfile.mkdtemp(prefix="gen-sql-"))
os.environ["DATABASE_PATH"] = str(tmp / "seed.db")
os.environ["SECRET_KEY"] = "gen-sql-only-not-a-real-key-0123456789abcdef"
os.environ["SEED_DEMO_DATA"] = "true"
os.environ["DEMO_AUTO_LOGIN"] = "false"
os.environ["ADMIN_USERNAME"] = ""
os.environ["ADMIN_PASSWORD"] = ""
sys.path.insert(0, str(PROJECT))

from sqlalchemy import select  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from app import __version__  # noqa: E402
from app.database import Base, SessionLocal, engine, migrate  # noqa: E402
from app.seed import seed  # noqa: E402

COMMENTS = {
    "users": "Login accounts (admin / teacher / student). password_hash = salted PBKDF2-SHA256 only.",
    "school_settings": "One row: school name, tagline, logo (validated data: URL), address, grading scale, currency.",
    "academic_years": "Academic years; one is current.",
    "classes": "Classes (Grade 1-10, Hifz Level 1-10 by default).",
    "sections": "Sections of a class.",
    "students": "The central student record.",
    "subjects": "Subjects with max/pass marks and credits.",
    "class_subjects": "Default subjects of a class.",
    "student_subjects": "Subjects a student takes.",
    "exams": "Exams; published exams are visible to students.",
    "marks": "Marks per student x exam x subject.",
    "attendance": "Daily attendance per student.",
    "fee_plans": "Monthly fee per class.",
    "payments": "Fee payments and receipts (voided, never deleted).",
    "periods": 'Periods of the school day ("HH:MM"); breaks hold no class.',
    "teacher_subjects": "Which teacher teaches which subject in a class (section NULL = every section).",
    "routine_slots": "Weekly class routine: subject and teacher per section, day and period.",
    "schema_migrations": "Numbered migrations applied by app/database.py migrate().",
    "app_settings": "1.0.5: SMTP / payment gateway / SMS settings, one row per field; secrets Fernet-encrypted.",
    "currencies": "1.0.5: currencies (one default = fees and receipts; others for display with a rate).",
    "languages": "1.0.5: interface languages (English, Bangla, Arabic RTL built in; more can be added).",
    "translations": "1.0.5: the administrator's own interface texts per language (override app/locales).",
}

dialect = engine.dialect
summary = []
for t in Base.metadata.sorted_tables:
    for fk in sorted(t.foreign_keys, key=lambda f: f.parent.name):
        indexed = any(fk.parent.name == idx.columns.keys()[0] for idx in t.indexes)
        summary.append(
            f"--   {t.name}.{fk.parent.name} -> {fk.column.table.name}.{fk.column.name}"
            f"  ON DELETE {fk.ondelete or 'NO ACTION'}  {'indexed' if indexed else 'NOT INDEXED'}"
        )
assert all("NOT INDEXED" not in s for s in summary), "every FK column must be indexed"
parts = [
    f"-- Madrasa Pro {__version__} - database schema (SQLite). Generated by tools/gen_schema_sql.py.",
    "-- Matches app/models.py exactly (tests/test_package_layout.py). The app creates/upgrades the",
    "-- database itself on start; this file is for inspection or a manual empty database:",
    '--   sqlite3 "Madrasa Admin Project/data/madrasa.db" < database/schema.sql',
    "-- PRAGMAs: foreign_keys=ON and journal_mode=WAL are set on EVERY connection (app/database.py).",
    f"-- Foreign keys ({len(summary)}), each with an index and an explicit ON DELETE rule:",
    *summary,
    "-- Extra indexes: attendance(date, student_id), payments(fee_month, student_id), marks(exam_id, student_id).",
    "",
    "PRAGMA foreign_keys = ON;",
    "",
]
for t in Base.metadata.sorted_tables:
    parts.append(f"-- {COMMENTS.get(t.name, t.name)}")
    ddl = str(CreateTable(t, if_not_exists=True).compile(dialect=dialect)).strip()
    parts.append("\n".join(line.rstrip().replace("\t", "    ") for line in ddl.splitlines() if line.strip()) + ";")
    for idx in sorted(t.indexes, key=lambda i: i.name):
        parts.append(str(CreateIndex(idx, if_not_exists=True).compile(dialect=dialect)).strip() + ";")
    parts.append("")
(ROOT / "database/schema.sql").write_text("\n".join(parts).rstrip() + "\n", encoding="utf-8")

migrate()
db = SessionLocal()
seed(db, demo=True)


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


out = [
    f"-- Madrasa Pro {__version__} - demo data (SQLite). Generated by tools/gen_schema_sql.py.",
    "-- Run AFTER database/schema.sql on an EMPTY database (optional; SEED_DEMO_DATA=true does the same):",
    '--   sqlite3 "Madrasa Admin Project/data/madrasa.db" < database/seed.sql',
    "-- Classes, subjects, students, marks, attendance, fees, periods, teacher assignments and a routine.",
    "-- It creates NO usable login: the first start opens /setup for your own administrator. The four",
    "-- sample teachers are DISABLED with no password. All names and phone numbers are made up.",
    "",
    "PRAGMA foreign_keys = ON;",
    "BEGIN TRANSACTION;",
    "",
]
for t in Base.metadata.sorted_tables:
    if t.name == "schema_migrations":
        continue
    rows = db.execute(select(t).order_by(*t.primary_key.columns)).all()
    if not rows:
        continue
    cols = [c.name for c in t.columns]
    collist = ", ".join(f'"{c}"' if c == "order" else c for c in cols)
    out.append(f"-- {t.name} ({len(rows)} rows)")
    out += [f"INSERT INTO {t.name} ({collist}) VALUES ({', '.join(q(v) for v in r)});" for r in rows]
    out.append("")
out.append("COMMIT;")
db.close()
(ROOT / "database/seed.sql").write_text("\n".join(out) + "\n", encoding="utf-8")
print("schema.sql + seed.sql written for", __version__)
